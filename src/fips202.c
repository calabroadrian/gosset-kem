#define ROTL(x, y) (((x) << (y)) | ((x) >> (64 - (y))))

/* generated by gen in v7: fully unrolled Keccak-f[1600] round body */
void keccakf(uint64_t s[25]) {
    uint64_t a0 = s[0], a1 = s[1], a2 = s[2], a3 = s[3], a4 = s[4], a5 = s[5], a6 = s[6], a7 = s[7], a8 = s[8], a9 = s[9], a10 = s[10], a11 = s[11], a12 = s[12], a13 = s[13], a14 = s[14], a15 = s[15], a16 = s[16], a17 = s[17], a18 = s[18], a19 = s[19], a20 = s[20], a21 = s[21], a22 = s[22], a23 = s[23], a24 = s[24];
    for (int r = 0; r < 24; r++) {
        uint64_t c0 = a0^a5^a10^a15^a20, c1 = a1^a6^a11^a16^a21, c2 = a2^a7^a12^a17^a22, c3 = a3^a8^a13^a18^a23, c4 = a4^a9^a14^a19^a24;
        uint64_t d0 = c4^ROTL(c1,1), d1 = c0^ROTL(c2,1), d2 = c1^ROTL(c3,1), d3 = c2^ROTL(c4,1), d4 = c3^ROTL(c0,1);
        uint64_t b0 = (a0^d0), b10 = ROTL((a1^d1),1), b20 = ROTL((a2^d2),62), b5 = ROTL((a3^d3),28), b15 = ROTL((a4^d4),27), b16 = ROTL((a5^d0),36), b1 = ROTL((a6^d1),44), b11 = ROTL((a7^d2),6), b21 = ROTL((a8^d3),55), b6 = ROTL((a9^d4),20), b7 = ROTL((a10^d0),3), b17 = ROTL((a11^d1),10), b2 = ROTL((a12^d2),43), b12 = ROTL((a13^d3),25), b22 = ROTL((a14^d4),39), b23 = ROTL((a15^d0),41), b8 = ROTL((a16^d1),45), b18 = ROTL((a17^d2),15), b3 = ROTL((a18^d3),21), b13 = ROTL((a19^d4),8), b14 = ROTL((a20^d0),18), b24 = ROTL((a21^d1),2), b9 = ROTL((a22^d2),61), b19 = ROTL((a23^d3),56), b4 = ROTL((a24^d4),14);
        a0 = b0 ^ (~b1 & b2);
        a1 = b1 ^ (~b2 & b3);
        a2 = b2 ^ (~b3 & b4);
        a3 = b3 ^ (~b4 & b0);
        a4 = b4 ^ (~b0 & b1);
        a5 = b5 ^ (~b6 & b7);
        a6 = b6 ^ (~b7 & b8);
        a7 = b7 ^ (~b8 & b9);
        a8 = b8 ^ (~b9 & b5);
        a9 = b9 ^ (~b5 & b6);
        a10 = b10 ^ (~b11 & b12);
        a11 = b11 ^ (~b12 & b13);
        a12 = b12 ^ (~b13 & b14);
        a13 = b13 ^ (~b14 & b10);
        a14 = b14 ^ (~b10 & b11);
        a15 = b15 ^ (~b16 & b17);
        a16 = b16 ^ (~b17 & b18);
        a17 = b17 ^ (~b18 & b19);
        a18 = b18 ^ (~b19 & b15);
        a19 = b19 ^ (~b15 & b16);
        a20 = b20 ^ (~b21 & b22);
        a21 = b21 ^ (~b22 & b23);
        a22 = b22 ^ (~b23 & b24);
        a23 = b23 ^ (~b24 & b20);
        a24 = b24 ^ (~b20 & b21);
        a0 ^= RC[r];
    }
    s[0] = a0; s[1] = a1; s[2] = a2; s[3] = a3; s[4] = a4; s[5] = a5; s[6] = a6; s[7] = a7; s[8] = a8; s[9] = a9; s[10] = a10; s[11] = a11; s[12] = a12; s[13] = a13; s[14] = a14; s[15] = a15; s[16] = a16; s[17] = a17; s[18] = a18; s[19] = a19; s[20] = a20; s[21] = a21; s[22] = a22; s[23] = a23; s[24] = a24;
}

void keccak_init(keccak_ctx *c, unsigned rate, uint8_t pad) {
    memset(c, 0, sizeof *c); c->rate = rate; c->pad = pad;
}

void keccak_absorb(keccak_ctx *c, const uint8_t *in, size_t len) {
    while (len) {
        size_t take = c->rate - c->pos; if (take > len) take = len;
        size_t i = 0;
        if ((c->pos & 7) == 0) for (; i + 8 <= take; i += 8) { uint64_t w; memcpy(&w, in + i, 8); c->st[(c->pos + i) / 8] ^= w; }
        for (; i < take; i++) c->st[(c->pos + i) / 8] ^= (uint64_t)in[i] << (8 * ((c->pos + i) % 8));
        c->pos += take; in += take; len -= take;
        if (c->pos == c->rate) { keccakf(c->st); c->pos = 0; }
    }
}

void keccak_finalize(keccak_ctx *c) {
    uint8_t p = c->pad;
    c->st[c->pos / 8] ^= (uint64_t)p << (8 * (c->pos % 8));
    c->st[(c->rate - 1) / 8] ^= (uint64_t)0x80 << (8 * ((c->rate - 1) % 8));
    keccakf(c->st);
    c->pos = 0;
}

void keccak_squeeze(keccak_ctx *c, uint8_t *out, size_t len) {
    while (len) {
        if (c->pos == c->rate) { keccakf(c->st); c->pos = 0; }
        size_t take = c->rate - c->pos; if (take > len) take = len;
        size_t i = 0;
        if ((c->pos & 7) == 0) for (; i + 8 <= take; i += 8) memcpy(out + i, &c->st[(c->pos + i) / 8], 8);
        for (; i < take; i++) out[i] = (uint8_t)(c->st[(c->pos + i) / 8] >> (8 * ((c->pos + i) % 8)));
        c->pos += take; out += take; len -= take;
    }
}

static void oneshot(unsigned rate, uint8_t pad, const uint8_t *in, size_t inlen, uint8_t *out, size_t outlen) {
    keccak_ctx c; keccak_init(&c, rate, pad); keccak_absorb(&c, in, inlen); keccak_finalize(&c); keccak_squeeze(&c, out, outlen);
}
void sha3_256(uint8_t out[32], const uint8_t *in, size_t len) { oneshot(136, 0x06, in, len, out, 32); }
void sha3_512(uint8_t out[64], const uint8_t *in, size_t len) { oneshot(72, 0x06, in, len, out, 64); }
void shake128(uint8_t *out, size_t outlen, const uint8_t *in, size_t len) { oneshot(168, 0x1F, in, len, out, outlen); }
void shake256(uint8_t *out, size_t outlen, const uint8_t *in, size_t len) { oneshot(136, 0x1F, in, len, out, outlen); }
